import { mkdir, readdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { build } from "esbuild";

const packageDirectory = path.dirname(fileURLToPath(import.meta.url));
const assets = path.join(packageDirectory, "assets");

async function packageFor(input) {
	let directory = path.dirname(
		path.resolve(packageDirectory, input.split("/").join(path.sep)),
	);
	while (directory !== packageDirectory) {
		try {
			const manifest = JSON.parse(
				await readFile(path.join(directory, "package.json"), "utf8"),
			);
			if (manifest.name && manifest.version) return { directory, manifest };
		} catch (error) {
			if (error.code !== "ENOENT") throw error;
		}
		const parent = path.dirname(directory);
		if (parent === directory) break;
		directory = parent;
	}
	throw new Error(`Cannot identify bundled dependency: ${input}`);
}

async function licenseNotices(inputs, name = "pull-request-renderers.js") {
	const packages = new Map();
	for (const input of inputs) {
		if (!input.split(/[\\/]/).includes("node_modules")) continue;
		const dependency = await packageFor(input);
		packages.set(
			`${dependency.manifest.name}@${dependency.manifest.version}`,
			dependency,
		);
	}
	const sections = [
		`Third-party notices for ${name}`,
		"Generated by build-renderers.mjs from the exact bundled dependency graph.",
	];
	for (const [name, { directory, manifest }] of [...packages].sort(
		([a], [b]) => (a < b ? -1 : a > b ? 1 : 0),
	)) {
		const files = (await readdir(directory))
			.filter((file) => /^(licen[sc]e|copying|notice)([.-]|$)/i.test(file))
			.sort();
		if (!files.length) throw new Error(`Missing license text for ${name}`);
		sections.push(
			`\n${"=".repeat(72)}\n${name}\nLicense: ${manifest.license ?? "See text below"}\n`,
		);
		for (const file of files) {
			sections.push(
				`--- ${file} ---\n${(await readFile(path.join(directory, file), "utf8")).replace(/\r\n/g, "\n").trim()}\n`,
			);
		}
	}
	return `${sections.join("\n").trimEnd()}\n`;
}

async function buildAsset(name, check) {
	const output = path.join(assets, `${name}.js`);
	const notices = path.join(assets, `${name}.LICENSE.txt`);
	const result = await build({
		absWorkingDir: packageDirectory,
		entryPoints: [path.join(packageDirectory, `${name}.mjs`)],
		outfile: output,
		bundle: true,
		format: "esm",
		platform: "browser",
		target: ["es2022"],
		minify: true,
		legalComments: "none",
		charset: "utf8",
		metafile: true,
		write: false,
		banner: {
			js: [
				"// @ts-nocheck -- Generated dependency bundle; TypeScript checks the source modules.",
				"// biome-ignore-all lint: Generated dependency bundle; edit source and rebuild.",
				"// biome-ignore-all assist/source/organizeImports: Generated dependency bundle; preserve esbuild output.",
				"// biome-ignore-all format: Generated dependency bundle; preserve esbuild output.",
				`/* Generated by ../build-renderers.mjs. Third-party licenses: ${name}.LICENSE.txt */`,
			].join("\n"),
		},
	});
	if (
		Object.values(result.metafile.outputs).some((item) => item.imports.length)
	) {
		throw new Error("Renderer bundle must not have runtime imports.");
	}
	const bundle = result.outputFiles[0].text;
	const licenses = await licenseNotices(
		Object.keys(result.metafile.inputs),
		`${name}.js`,
	);
	if (check) {
		for (const [file, expected] of [
			[output, bundle],
			[notices, licenses],
		]) {
			if ((await readFile(file, "utf8")) !== expected) {
				throw new Error(
					`${path.basename(file)} is stale; run node build-renderers.mjs from the extension package.`,
				);
			}
		}
	} else {
		await mkdir(assets, { recursive: true });
		await writeFile(output, bundle);
		await writeFile(notices, licenses);
	}
	return {
		bundleBytes: Buffer.byteLength(bundle),
		licenseBytes: Buffer.byteLength(licenses),
	};
}

/** Run with node build-renderers.mjs [--check]; bundles have no runtime imports. */
export async function buildRenderers({ check = false } = {}) {
	const renderers = await buildAsset("pull-request-renderers", check);
	const diff = await buildAsset("pull-request-diff", check);
	return {
		bundleBytes: renderers.bundleBytes + diff.bundleBytes,
		licenseBytes: renderers.licenseBytes + diff.licenseBytes,
	};
}

if (
	process.argv[1] &&
	path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)
) {
	console.log(
		await buildRenderers({ check: process.argv.includes("--check") }),
	);
}
